"""Build the de-duplicated pool and all split manifests; verify disjointness; write reports/split_report.md"""
import _bootstrap, argparse, zipfile
import numpy as np, pandas as pd
from src.common import ROOT, load_config, data_dir, write_json, sha256_file
from src.data.loading import load_split
from src.data import splits as S
from src.data.urls import registered_domain, hostname, normalise_url

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--dataset-zip", default=None); a = ap.parse_args()
    cfg = load_config(); dd = data_dir(cfg)
    if a.dataset_zip:
        h = sha256_file(a.dataset_zip)
        if h != cfg["data"]["expected_zip_sha256"]: raise SystemExit(f"ZIP hash mismatch: {h}")
        dd.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(a.dataset_zip) as z: z.extractall(dd)
    out = ROOT / cfg["processed_dir"]; out.mkdir(parents=True, exist_ok=True)
    pool, ex = S.build_pool(load_split("master", cfg))
    rec, ex_r = S.build_pool(load_split("recent", cfg))
    pool.to_pickle(out / "pool.pkl"); rec.to_pickle(out / "recent.pkl")
    report = {"pool_exclusions": ex, "recent_exclusions": ex_r, "protocols": {}}
    # recent: rows whose registered domain also occurs in pool (reported; evaluation uses both views)
    rec["rd_in_pool"] = rec["rd"].isin(set(pool["rd"]))
    report["recent_rd_in_pool_rows"] = int(rec["rd_in_pool"].sum())
    for proto, lvl in [("random", "url"), ("hostname", "hostname"), ("regdomain", "regdomain")]:
        for seed in cfg["seeds"] if proto == "regdomain" else [cfg["seed"]]:
            sp = S.make_split(pool, proto, seed)
            v = S.verify_split(pool, sp, lvl)
            if proto != "random" and not v["disjoint_at_level"]: raise SystemExit(f"{proto} split leaks at {lvl}")
            v["checksum"] = S.split_checksum(pool["row_id"].values, sp)
            name = f"{proto}_seed{seed}"; report["protocols"][name] = v
            pd.DataFrame({"row_id": pool["row_id"], "split": sp}).to_csv(out / f"split_{name}.csv.gz", index=False)
    srcs = ("PhiUSIIL", "Mendeley-450K")
    for tr, te in [srcs, srcs[::-1]]:
        sp = S.source_heldout(pool, tr, te, cfg["seed"])
        v = S.verify_split(pool, sp, "regdomain"); v["checksum"] = S.split_checksum(pool["row_id"].values, sp)
        v["excluded_rows"] = int((sp == "drop").sum())
        name = f"source_{tr}_to_{te}"; report["protocols"][name] = v
        pd.DataFrame({"row_id": pool["row_id"], "split": sp}).to_csv(out / f"split_{name}.csv.gz", index=False)
        if not v["disjoint_at_level"]: raise SystemExit("source split leaks")
    report["chronological"] = "NOT SUPPORTED: no timestamps/provenance in supplied data"
    write_json(report, ROOT / "results" / "split_report.json")
    L = ["# Split construction and leakage verification", "", "_Generated by `scripts/prepare_data.py` (status: executed and verified)._", "",
         f"Pool: master_training_candidate.csv, {ex['input_rows']:,} rows → {ex['pool_rows']:,} after exclusions: {ex}.", "",
         f"Recent external holdout: {ex_r}; rows whose registered domain also occurs in the pool: {report['recent_rd_in_pool_rows']:,}.", ""]
    for n, v in report["protocols"].items():
        L += [f"## {n}", "", "| part | rows | phishing | phish % |", "|---|---:|---:|---:|"]
        L += [f"| {p} | {c['rows']:,} | {c['phishing']:,} | {c['phish_pct']} |" for p, c in v["counts"].items()]
        L += ["", "Overlap (distinct keys shared) per partition pair:", "", "| pair | url | hostname | registered domain |", "|---|---:|---:|---:|"]
        L += [f"| {k} | {o['url']} | {o['hostname']} | {o['regdomain']} |" for k, o in v["overlap"].items()]
        L += ["", f"Disjoint at the protocol's level: **{v['disjoint_at_level']}**; checksum `{v['checksum'][:16]}…`", ""]
    L += ["The `random` split is a reference baseline only: it shares hostnames and registered domains across partitions by construction.",
          "Chronological split: **not supported by the available data** (no timestamps)."]
    (ROOT / "reports" / "split_report.md").write_text("\n".join(L) + "\n")
    print("ok", ex)
if __name__ == "__main__": main()
